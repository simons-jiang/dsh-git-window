/**
 * Assemble `client.js` from the readable fragments in `src/client`.
 *
 * The browser module loader takes ONE file per package id, so the sources are
 * concatenated into a single factory body inside the loader envelope. Locale
 * dictionaries are inlined from `locale/*.json` (the same files the Plugin
 * Manager reads for the display title and description), so UI copy has exactly
 * one source of truth.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'))
const sourceDir = join(here, 'src', 'client')
const files = (await readdir(sourceDir)).filter((name) => name.endsWith('.js')).sort()

/** Strip the display metadata the Plugin Manager reads. */
async function dictionary(locale) {
  const document = JSON.parse(await readFile(join(here, 'locale', `${locale}.json`), 'utf8'))
  const entries = Object.entries(document).filter(([key]) => key !== 'meta')
  const body = entries.map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n')
  return `  const GW_TEXT_${locale.toUpperCase()} = {\n${body}\n  }`
}

const fragments = []
for (const name of files) {
  const text = await readFile(join(sourceDir, name), 'utf8')
  fragments.push(`// ---- ${name} ${'-'.repeat(Math.max(0, 68 - name.length))}\n${text.trim()}\n`)
}

const envelope = `/**
 * dsh-git-window — Client half. Generated by build.mjs from src/client/*.js;
 * edit those sources, then run \`node build.mjs\`.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react')
    const { useCallback, useEffect, useMemo, useRef, useState, useSyncExternalStore } = React
    const h = React.createElement
${await dictionary('en')}
${await dictionary('zh')}

${fragments.join('\n')}
    return { inject: ['slots', 'locale'], apply }
  },
})
`

await writeFile(join(here, 'client.js'), envelope, 'utf8')
console.log(`client.js: ${files.length} fragments, ${envelope.length} bytes`)
